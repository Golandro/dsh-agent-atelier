#!/usr/bin/env node
/**
 * Build the two package-local lazy chunks (ticket 05) into the artifact shapes
 * the DSH module loader's on-demand chunk channel expects:
 *
 *   client-editor/index.ts → lib/client.editor.js  (IIFE, react-free CodeMirror)
 *   client-list/index.tsx  → lib/client.list.js    (CJS, external = react only)
 *
 * Q4 ruling (2026-10-19): browser release artifact, local, no CDN, fully lazy.
 * Vite (an existing devDependency) produces the self-contained browser bundle;
 * the wrapper emitted below registers via
 * `window.__ModuleLoader__.load({ id, chunk, factory })` — the exact shape
 * `require.async('./client.<name>.js')` resolves against (DSH `client/modules`
 * `client/system.ts`: `CLIENT_CHUNK` name rule + classic script-tag import).
 * The chunk name MUST stay `client.<name>.js` and the factory's only external
 * for the list chunk is the platform `react` seed word.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { build } from 'vite'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PACKAGE_NAME = 'dsh-plugin-agents-manager'
const STAGE_DIR = join(ROOT, 'lib/.chunk-build')

const esbuildJsx = { jsx: 'transform', jsxFactory: 'h' }

/** Build one chunk source with vite's library mode and return the JS text. */
async function buildChunk({ entry, formats, globalName, external, outDir }) {
  await build({
    configFile: false,
    root: ROOT,
    logLevel: 'warn',
    esbuild: esbuildJsx,
    // 浏览器里没有 Node 的 process：依赖（react/tanstack/codemirror）都会读
    // process.env.NODE_ENV，不在这里静态替换就会在 chunk 加载时报
    // "process is not defined"（列表/编辑器整个 chunk 起不来）。
    define: { 'process.env.NODE_ENV': JSON.stringify('production') },
    build: {
      target: 'es2022',
      minify: false,
      outDir,
      emptyOutDir: true,
      lib: {
        entry: resolve(ROOT, entry),
        formats,
        ...(globalName === undefined ? {} : { name: globalName }),
        fileName: (format) => `chunk.${format}.js`,
      },
      rollupOptions: external === undefined ? {} : { external, output: { exports: 'named' } },
    },
  })
  return readFileSync(join(outDir, `chunk.${formats[0]}.js`), 'utf8')
}

/** Registration shape for package-local chunks (`client/system.ts` register()). */
function wrapChunk({ chunkFile, factoryBody }) {
  return `/* generated by scripts/build-chunks.mjs — do not edit */
window.__ModuleLoader__.load({
  id: "${PACKAGE_NAME}",
  chunk: ${JSON.stringify(chunkFile)},
  factory: ${factoryBody},
});
`
}

const editorCode = await buildChunk({
  entry: 'client-editor/index.ts',
  formats: ['iife'],
  globalName: 'AgentsManagerEditor',
  outDir: join(STAGE_DIR, 'editor'),
})
const editorBundle = wrapChunk({
  chunkFile: 'client.editor.js',
  factoryBody: `() => {
${editorCode}
return AgentsManagerEditor;
}`,
})

const listCode = await buildChunk({
  entry: 'client-list/index.tsx',
  formats: ['cjs'],
  external: ['react'],
  outDir: join(STAGE_DIR, 'list'),
})
const listBundle = wrapChunk({
  chunkFile: 'client.list.js',
  factoryBody: `(require) => {
var module = { exports: {} };
var exports = module.exports;
${listCode}
return module.exports;
}`,
})

mkdirSync(join(ROOT, 'lib'), { recursive: true })
writeFileSync(join(ROOT, 'lib/client.editor.js'), editorBundle)
writeFileSync(join(ROOT, 'lib/client.list.js'), listBundle)
rmSync(STAGE_DIR, { recursive: true, force: true })
console.log(`built lib/client.editor.js (${editorBundle.length} bytes), lib/client.list.js (${listBundle.length} bytes)`)
